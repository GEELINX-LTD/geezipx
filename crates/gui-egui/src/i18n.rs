//! Desktop language choices and the shared Chinese/English message catalog.
use serde::{Deserialize, Serialize};

#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Serialize, Deserialize)]
pub enum Language {
    #[serde(rename = "en")]
    English,
    #[default]
    #[serde(rename = "zh_cn", other)]
    Chinese,
}

impl Language {
    pub const ALL: [Self; 2] = [Self::Chinese, Self::English];

    pub fn label(self) -> &'static str {
        match self {
            Self::Chinese => "简体中文",
            Self::English => "English",
        }
    }

    pub fn select<'a>(self, chinese: &'a str, english: &'a str) -> &'a str {
        match self {
            Self::Chinese => chinese,
            Self::English => english,
        }
    }
}

// Each key has both translations. Unknown keys fail at compile time; format!
// checks the arguments of both languages, preserving paths and external errors.
macro_rules! messages {
    ($($key:ident => ($zh:literal, $en:literal)),* $(,)?) => {
        #[doc(hidden)]
        #[macro_export]
        macro_rules! message_zh {
            $(($key) => { $zh };)*
        }
        #[doc(hidden)]
        #[macro_export]
        macro_rules! message_en {
            $(($key) => { $en };)*
        }
    };
}

#[macro_export]
macro_rules! tr {
    ($language:expr, $key:ident $(,)?) => {
        $language.select($crate::i18n::message_zh!($key), $crate::i18n::message_en!($key))
    };
    ($language:expr, $key:ident, $($args:tt)+) => {
        match $language {
            $crate::i18n::Language::Chinese => format!($crate::i18n::message_zh!($key), $($args)+),
            $crate::i18n::Language::English => format!($crate::i18n::message_en!($key), $($args)+),
        }
    };
}

